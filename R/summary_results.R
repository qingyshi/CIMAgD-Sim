# Summarize saved replication-level RDS files, with no simulation reruns.
# Rscript summary_results.R --input=results --output=simulation_summary
# Smoke outputs are marked as validation output in every caption and figure.

summary_settings <- c("1trial_binary_main", "5trial_binary_main",
                      "1trial_continuous_add", "5trial_binary_small_add")
summary_titles <- c("Single trial, binary outcome", "Five trials, binary outcome",
                    "Single trial, continuous outcome", "Five small trials, binary outcome")
summary_methods <- c("CIMAgD", "IPD-PO", "IPD-GF", "Meta", "Meta-reg")

summary_read <- function(path, setting) {
  files <- list.files(path, pattern = "^scenario_[0-9]+[.]rds$", full.names = TRUE)
  if (!length(files)) return(NULL)
  saved <- lapply(files, readRDS)
  for (s in saved) {
    if (!identical(s$schema_version, 1L) || !identical(s$setting, setting))
      stop("Unexpected schema or setting in ", path)
    required <- c("setting", "scenario", "replication", "method", "truth", "estimate",
                  "se", "lower", "upper", "success", "error", "warning")
    if (!all(required %in% names(s$results))) stop("Incomplete replication data in ", path)
    if (!identical(s$scenario_table, saved[[1]]$scenario_table)) stop("Scenario specifications differ")
    if (!identical(s$package_versions, saved[[1]]$package_versions)) stop("Package versions differ")
    if (!identical(s$implementation_md5, saved[[1]]$implementation_md5)) stop("Simulation implementations differ")
  }
  d <- do.call(rbind, lapply(saved, `[[`, "results"))
  if (anyDuplicated(d[c("setting", "scenario", "replication", "method")])) stop("Duplicate replication records")
  expected <- summary_methods[if (startsWith(setting, "5trial")) 1:5 else 1:3]
  groups <- split(d, interaction(d$scenario, d$replication, drop = TRUE))
  if (any(!vapply(groups, function(x) setequal(x$method, expected), logical(1))))
    stop("Missing or unexpected method records")
  for (s in unique(d$scenario)) {
    truth <- unique(d$truth[d$scenario == s])
    if (length(truth) != 1L || !is.finite(truth)) stop("Inconsistent or nonfinite population truth")
  }
  list(data = d, scenarios = saved[[1]]$scenario_table, metadata = saved)
}

summary_metrics <- function(d) {
  groups <- split(d, interaction(d$scenario, d$method, drop = TRUE))
  result <- lapply(groups, function(g) {
    ok <- g$success & is.finite(g$estimate) & is.finite(g$se) & g$se >= 0 &
      is.finite(g$lower) & is.finite(g$upper)
    x <- g$estimate[ok]; err <- x - g$truth[ok]; n <- length(x)
    mean_or_na <- function(x) if (length(x)) mean(x) else NA_real_
    mcse <- function(x) if (length(x) > 1L) sd(x) / sqrt(length(x)) else NA_real_
    covered <- g$lower[ok] <= g$truth[ok] & g$upper[ok] >= g$truth[ok]
    coverage <- mean_or_na(covered)
    data.frame(setting = g$setting[1], scenario = g$scenario[1], method = g$method[1],
      truth = g$truth[1], attempted = nrow(g), successful = n, failed = nrow(g) - n,
      failure_rate = 1 - n / nrow(g), bias = mean_or_na(err),
      variance = if (n > 1L) var(x) else NA_real_,
      empirical_sd = if (n > 1L) sd(x) else NA_real_, mean_se = mean_or_na(g$se[ok]),
      coverage = coverage, coverage_all = sum(covered) / nrow(g),
      mse = mean_or_na(err^2), mae = mean_or_na(abs(err)),
      mcse_bias = mcse(err),
      mcse_variance = if (n > 2L) mcse((x - mean_or_na(x))^2) else NA_real_,
      mcse_coverage = if (n > 1L) sqrt(coverage * (1 - coverage) / n) else NA_real_,
      mcse_mse = mcse(err^2), mcse_mae = mcse(abs(err)))
  })
  ans <- do.call(rbind, result)
  ans <- ans[order(ans$scenario, match(ans$method, summary_methods)), ]
  rownames(ans) <- NULL
  ans
}

summary_fmt <- function(x, percent = FALSE) {
  if (!is.finite(x)) return("--")
  if (percent) return(sprintf("%.1f", 100 * x))
  if (x != 0 && abs(x) < .0001) {
    bits <- strsplit(sprintf("%.2e", x), "e", fixed = TRUE)[[1]]
    return(paste0("$", bits[1], "\\times10^{", as.integer(bits[2]), "}$"))
  }
  sprintf("%.4f", x)
}

summary_table <- function(s, metrics, labels, caption, label, note = "") {
  methods <- summary_methods[summary_methods %in% s$method]
  k <- length(metrics)
  lines <- c("% Generated by summary_results.R; requires booktabs and graphicx.",
    "\\begin{table}[htbp]", "\\centering", "\\small",
    paste0("\\caption{", caption, "}"), paste0("\\label{", label, "}"),
    "\\resizebox{\\textwidth}{!}{%", paste0("\\begin{tabular}{r", paste(rep("r", k * length(methods)), collapse = ""), "}"),
    "\\toprule", paste0("Scenario & ", paste(paste0("\\multicolumn{", k, "}{c}{", methods, "}"), collapse = " & "), " \\\\"))
  lines <- c(lines, paste0(" & ", paste(rep(labels, length(methods)), collapse = " & "), " \\\\") , "\\midrule")
  for (i in sort(unique(s$scenario))) {
    vals <- unlist(lapply(methods, function(m) {
      row <- s[s$scenario == i & s$method == m, ]
      vapply(metrics, function(metric) {
        if (!nrow(row)) return("--")
        if (metric %in% c("successful", "failed", "attempted")) return(as.character(row[[metric]]))
        summary_fmt(row[[metric]], grepl("coverage|failure_rate", metric))
      }, "")
    }))
    lines <- c(lines, paste0(i, " & ", paste(vals, collapse = " & "), " \\\\"))
  }
  c(lines, "\\bottomrule", "\\end{tabular}%", "}",
    if (nzchar(note)) c("\\par\\smallskip", paste0("\\begin{minipage}{\\textwidth}\\footnotesize ", note, "\\end{minipage}")),
    "\\end{table}", "")
}

summary_plot <- function(s, out, title, validation) {
  methods <- summary_methods[summary_methods %in% s$method]
  s$method <- factor(s$method, levels = methods)
  s$scenario <- factor(s$scenario, levels = sort(unique(s$scenario)))
  # Named colours keep each method identical in the bars, lines, and all settings.
  palette <- c(CIMAgD = "#0072B2", `IPD-PO` = "#E69F00", `IPD-GF` = "#009E73",
               Meta = "#CC79A7", `Meta-reg` = "#D55E00")
  sqrt_metrics <- any(startsWith(s$setting, "5trial")) &&
    any(methods %in% c("Meta", "Meta-reg"))
  plot_theme <- ggplot2::theme_minimal(base_size = 11) +
    ggplot2::theme(panel.grid.minor.x = ggplot2::element_blank())

  bar_plot <- function(metric, label, show_scenarios = FALSE, sqrt_axis = FALSE) {
    d <- data.frame(scenario = s$scenario, method = s$method, value = s[[metric]])
    p <- ggplot2::ggplot(d, ggplot2::aes(x = scenario, y = value, fill = method)) +
      ggplot2::geom_col(position = ggplot2::position_dodge(width = .9),
                        width = .9, na.rm = TRUE) +
      ggplot2::scale_fill_manual(values = palette, breaks = methods, name = "Method", drop = FALSE) +
      ggplot2::scale_x_discrete(drop = FALSE) +
      ggplot2::labs(x = "Scenarios", y = label, title = label) +
      plot_theme
    if (sqrt_axis) p <- p + ggplot2::scale_y_continuous(transform = "sqrt")
    if (!show_scenarios) p <- p + ggplot2::theme(axis.text.x = ggplot2::element_blank())
    p
  }

  p_bias <- bar_plot("bias", "Bias", show_scenarios = TRUE) +
    ggplot2::geom_hline(yintercept = 0, colour = "grey70", linewidth = .3)
  p_var <- bar_plot("variance", "Variance", sqrt_axis = sqrt_metrics)
  p_mse <- bar_plot("mse", "MSE", sqrt_axis = sqrt_metrics)
  p_coverage <- ggplot2::ggplot(s, ggplot2::aes(x = scenario, y = coverage,
                                               colour = method, group = method)) +
    ggplot2::geom_line(linewidth = 1, na.rm = TRUE, show.legend = FALSE) +
    ggplot2::geom_hline(yintercept = .95, linetype = "dashed", colour = "grey25", linewidth = .7) +
    ggplot2::scale_colour_manual(values = palette, breaks = methods, name = "Method", drop = FALSE) +
    ggplot2::scale_x_discrete(drop = FALSE) +
    ggplot2::scale_y_continuous(limits = c(0, 1), breaks = c(.5, .75, .95)) +
    ggplot2::labs(x = "Scenarios", y = "95% CI coverage", title = "Coverage") +
    plot_theme + ggplot2::theme(axis.text.x = ggplot2::element_blank())

  # Historical layout: bias fills the left half; coverage sits above the two
  # smaller variance/MSE panels on the right. Only their five-trial axes use sqrt.
  p <- patchwork::wrap_plots(A = p_bias, B = p_coverage, C = p_var, D = p_mse,
                             design = "AABB\nAACD", guides = "collect") +
    patchwork::plot_annotation(title = title,
      subtitle = NULL,
      caption = paste0(if (sqrt_metrics) "\nVariance and MSE use square-root axes." else ""),
      theme = ggplot2::theme(plot.title = ggplot2::element_text(size = 14),
                             plot.subtitle = ggplot2::element_text(size = 11),
                             plot.caption = ggplot2::element_text(size = 9)))
  p <- p & ggplot2::theme(legend.position = "bottom")
  ggplot2::ggsave(file.path(out, "figure.pdf"), p, width = 13, height = 7, bg = "white")
  ggplot2::ggsave(file.path(out, "figure.png"), p, width = 13, height = 7, dpi = 300, bg = "white")
  ggplot2::ggsave(file.path(out, "figure.eps"), p, width = 13, height = 7, dpi = 300, bg = "white")
  invisible(p)
}

summary_run <- function(args = commandArgs(trailingOnly = TRUE)) {
  if (any(args %in% c("--help", "-h"))) {
    cat("Rscript summary_results.R --input=results --output=simulation_summary [--settings=all]\n")
    return(invisible(NULL))
  }
  options <- list(input = "results", output = "simulation_summary", settings = "all")
  for (a in args) {
    if (!grepl("^--(input|output|settings)=.+$", a)) stop("Unknown argument: ", a)
    key <- sub("^--([^=]+)=.*$", "\\1", a)
    options[[key]] <- sub("^--[^=]+=", "", a)
  }
  settings <- if (options$settings == "all") summary_settings else
    strsplit(options$settings, ",", fixed = TRUE)[[1]]
  if (any(!settings %in% summary_settings)) stop("Unknown setting")
  if (!requireNamespace("ggplot2", quietly = TRUE)) stop("Install ggplot2 for the figures")
  if (!requireNamespace("patchwork", quietly = TRUE)) stop("Install patchwork for the figure layout")
  processed <- 0L
  for (setting in settings) {
    loaded <- summary_read(file.path(options$input, setting), setting)
    if (is.null(loaded)) { message("No saved results for ", setting); next }
    s <- summary_metrics(loaded$data)
    out <- file.path(options$output, setting)
    dir.create(out, recursive = TRUE, showWarnings = FALSE)
    validation <- any(s$attempted < 1000L) || !setequal(unique(s$scenario), 1:16)
    title <- summary_titles[match(setting, summary_settings)]
    prefix <- if (validation) "Validation run only. " else ""
    note <- paste("Metrics use successful fits; failures are not replaced or resimulated.",
      "IPD-PO: pseudo-outcome regression; IPD-GF: g-formula.",
      "Dashes indicate undefined quantities (including variance with fewer than two successful fits).")
    groups <- list(bias_variance = list(c("bias", "variance"), c("Bias", "Variance")),
                   coverage = list("coverage", "Coverage (\\%)"),
                   fit_counts = list(c("successful", "attempted"), c("Success", "Attempted")),
                   mse_mae = list(c("mse", "mae"), c("MSE", "MAE")))
    captions <- c(bias_variance = "bias and variance", coverage = "coverage",
                  fit_counts = "successful and attempted fits", mse_mae = "MSE and MAE")
    for (name in names(groups)) {
      g <- groups[[name]]
      table_note <- note
      if (name == "coverage") {
        methods <- summary_methods[summary_methods %in% s$method]
        ranges <- vapply(methods, function(m) {
          values <- s$coverage[s$method == m & is.finite(s$coverage)]
          if (!length(values)) return(paste0(m, ": --"))
          paste0(m, ": ", summary_fmt(min(values), percent = TRUE), "--",
                 summary_fmt(max(values), percent = TRUE), "\\%")
        }, character(1))
        table_note <- paste("Coverage is computed among successful fits.",
          "IPD-PO: pseudo-outcome regression; IPD-GF: g-formula.",
          "Coverage ranges across scenarios (minimum--maximum):",
          paste0(paste(ranges, collapse = "; "), "."),
          "Dashes indicate undefined coverage; ranges use only scenarios with defined coverage.")
      }
      writeLines(summary_table(s, g[[1]], g[[2]], paste0(prefix, title, ": ",
        captions[[name]], "."), paste0("tab:", gsub("_", "-", setting), "-", name),
        table_note), file.path(out, paste0(name, ".tex")))
    }
    mcse_lines <- character()
    for (m in summary_methods[summary_methods %in% s$method]) mcse_lines <- c(mcse_lines,
      summary_table(s[s$method == m, ], c("mcse_bias", "mcse_variance", "mcse_coverage", "mcse_mse", "mcse_mae"),
        c("Bias", "Variance", "Coverage (pp)", "MSE", "MAE"),
        paste0(prefix, title, ": Monte Carlo standard errors for ", m, "."),
        paste0("tab:", gsub("_", "-", setting), "-mcse-", m),
        "Coverage MCSE is in percentage points; variance MCSE uses an empirical influence-function approximation and requires at least three successful fits."))
    writeLines(mcse_lines, file.path(out, "mcse.tex"))
    saveRDS(list(summary = s, scenarios = loaded$scenarios,
                parameters = lapply(loaded$metadata, `[[`, "parameters"),
                implementation_md5 = loaded$metadata[[1]]$implementation_md5,
                package_versions = loaded$metadata[[1]]$package_versions),
            file.path(out, "summary.rds"))
    failures <- loaded$data[!loaded$data$success | nzchar(loaded$data$warning), ]
    saveRDS(failures, file.path(out, "fit_messages.rds"))
    writeLines(c(paste("Setting:", setting), paste("Validation only:", validation),
      paste("Replications per method/scenario:", paste(range(s$attempted), collapse = "--")),
      paste("Failed fits:", sum(s$failed)),
      if (!nrow(failures)) "No fitting errors or warnings." else
        apply(failures[, c("scenario", "replication", "method", "error", "warning")], 1, paste, collapse = " | ")),
      file.path(out, "fit_messages.txt"))
    summary_plot(s, out, title, validation)
    message("Saved LaTeX tables, figures, summaries, and fitting messages: ", out)
    processed <- processed + 1L
  }
  if (!processed) stop("No scenario RDS files found; specify the simulation output root with --input.")
  invisible(processed)
}

if (sys.nframe() == 0L) summary_run()
